create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  level text not null default 'A1' check (level in ('A1','A2','B1','B2','C1')),
  daily_goal integer not null default 5 check (daily_goal between 1 and 50),
  streak integer not null default 0,
  last_study_date date,
  created_at timestamptz not null default now()
);

create table public.words (
  id bigint generated by default as identity primary key,
  english text not null unique,
  turkish text not null,
  level text not null check (level in ('A1','A2','B1','B2','C1')),
  phonetic text,
  example_en text,
  example_tr text,
  created_at timestamptz not null default now()
);

create table public.user_words (
  user_id uuid not null references auth.users(id) on delete cascade,
  word_id bigint not null references public.words(id) on delete cascade,
  repetitions integer not null default 0,
  ease_factor numeric not null default 2.5,
  interval_days integer not null default 0,
  next_review date not null default current_date,
  last_result integer,
  learned_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, word_id)
);

alter table public.profiles enable row level security;
alter table public.words enable row level security;
alter table public.user_words enable row level security;

create policy "words readable by everyone" on public.words for select using (true);
create policy "profiles own row" on public.profiles for all using (auth.uid() = id) with check (auth.uid() = id);
create policy "user words own rows" on public.user_words for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
